-- Province e comuni d'Italia. Le province sono precaricate qui (107); i comuni con CAP e provincia si scaricano da internet
-- all'avvio (GeoDataImporter) oppure da Amministrazione > Province e comuni.
CREATE TABLE province (
    id      BIGSERIAL PRIMARY KEY,
    sigla   VARCHAR(2)   NOT NULL UNIQUE,
    nome    VARCHAR(100) NOT NULL,
    regione VARCHAR(60)
);

CREATE TABLE comuni (
    id          BIGSERIAL PRIMARY KEY,
    istat_code  VARCHAR(6),
    nome        VARCHAR(150) NOT NULL,
    province_id BIGINT       NOT NULL REFERENCES province (id),
    cap         VARCHAR(5),                 -- CAP principale (il primo)
    cap_list    VARCHAR(600),               -- tutti i CAP, separati da virgola (citta' con piu' CAP)
    catastale   VARCHAR(4)
);
CREATE UNIQUE INDEX ux_comuni_istat ON comuni (istat_code) WHERE istat_code IS NOT NULL;
CREATE INDEX ix_comuni_nome ON comuni (lower(nome) text_pattern_ops);
CREATE INDEX ix_comuni_province ON comuni (province_id);

